// The attestation record of AIR-303 and the two seams its verifier needs. Facts and URLs: research repo notes/nearai_attestation_2026-11-03.md.

/** One named check. `ok` false is a failure with a reason in `detail`; the console prints these rows and no verdict word of its own. */
export interface Check {
  name: string;
  ok: boolean;
  detail: string;
}

/**
 * VERIFIED: every check passed. FAILED: a report arrived and a check failed. UNATTESTED: no report could be fetched (no key, network, HTTP
 * error, no `model_attestations`), so nothing was checked. Never anything else, and never silent: a receipt always carries one of the three.
 */
export type AttestStatus = 'VERIFIED' | 'FAILED' | 'UNATTESTED';

export interface Attestation {
  model: string;
  /** 64 hex characters, generated by this client for this fetch */
  nonce: string;
  /** sha256 of the raw HTTP response body that was verified; empty for UNATTESTED */
  report_sha256: string;
  /** ISO time the verification ran */
  verified_at: string;
  status: AttestStatus;
  checks: Check[];
  /** model signing identity (ecdsa address) and Intel TCB status, for the receipt; null when no report was read */
  signing_address: string | null;
  tcb_status: string | null;
  /** compose hash of the measured model configuration, from the verified MRCONFIGID; null when not read */
  compose_hash: string | null;
  /** `live`: fetched and verified in this process. `recorded`: a stored record served by a replay server, never re-verified there. */
  source: 'live' | 'recorded';
}

/** What the verifier reads out of one Intel TDX quote after the DCAP signature, collateral and TCB checks. Bytes are lowercase hex. */
export interface VerifiedQuote {
  status: string;
  advisory_ids: string[];
  td_attributes: string;
  report_data: string;
  mr_config_id: string;
  rtmr3: string;
  mr_td: string;
}

/** Verifies the Intel quote (hex) and throws when the quote or its collateral is invalid. */
export type QuoteVerifier = (quoteHex: string) => Promise<VerifiedQuote>;

/** Sends a decoded NVIDIA evidence payload to NRAS and returns its `x-nvidia-overall-att-result`, or throws. */
export type GpuVerifier = (payload: unknown) => Promise<boolean>;

export interface VerifyDeps {
  verifyQuote: QuoteVerifier;
  verifyGpu: GpuVerifier;
  now: () => Date;
}

export interface VerifyPolicy {
  /** Intel TCB statuses accepted; the default is `UpToDate` only */
  acceptedTcb: readonly string[];
  /** when set, the model's compose hash must be one of these (an allowlist of measured configurations) */
  acceptedComposeHashes?: readonly string[];
}

export const DEFAULT_POLICY: VerifyPolicy = { acceptedTcb: ['UpToDate'] };
