#!/usr/bin/env bash
# usage: scripts/plumbing-doc.sh [--check]
# AIR-241: renders the plumbing index (scripts/plumbing-index.sh, then scripts/plumbing-ts-rows.txt) as a Markdown table between
# <!-- plumbing:start --> and <!-- plumbing:end --> in docs/PLUMBING.md. Only the lines between the markers change; when the markers are
# absent the section is appended. --check rewrites nothing and exits 1 when the table is stale or when a row's test name does not occur
# (grep -F) in its file (a row whose test is the file itself must only exist). Last line `PLUMBING DOC OK <n> lines` or `PLUMBING DOC STALE`.
set -euo pipefail
repo="$(cd "$(dirname "$0")/.." && pwd)"
cd "$repo"
doc="${PLUMBING_DOC:-docs/PLUMBING.md}"
ts_rows="${PLUMBING_TS_ROWS:-scripts/plumbing-ts-rows.txt}"
index="${PLUMBING_INDEX:-scripts/plumbing-index.sh}"
start='<!-- plumbing:start -->'
end='<!-- plumbing:end -->'
mode="${1:-}"
case "$mode" in '' | --check) ;; *) echo "usage: scripts/plumbing-doc.sh [--check]"; exit 2 ;; esac

rows="$("$index" | grep -v '^PLUMBING INDEX OK')" || { echo "FAIL the plumbing index did not pass"; exit 1; }
if [ -f "$ts_rows" ]; then rows="$rows"$'\n'"$(grep -vE '^(#|[[:space:]]*$)' "$ts_rows")"; fi

bad=0
while IFS= read -r row; do
  [ -z "$row" ] && continue
  name="$(printf '%s' "$row" | awk -F' [|] ' '{print $2}')"
  file="$(printf '%s' "$row" | awk -F' [|] ' '{print $3}')"
  if [ ! -f "$file" ]; then echo "FAIL missing file $file"; bad=1
  elif [ "$name" != "$file" ] && ! grep -qF -- "$name" "$file"; then echo "FAIL test name not in $file: $name"; bad=1; fi
done <<< "$rows"
[ "$bad" -eq 0 ] || exit 1

table="$(printf '| Class | Test | File |\n| --- | --- | --- |\n'; printf '%s\n' "$rows" | grep -v '^$' | awk -F' [|] ' '{printf "| %s | %s | %s |\n", $1, $2, $3}')"
block="$start"$'\n'"$table"$'\n'"$end"

if grep -qF "$start" "$doc" && grep -qF "$end" "$doc"; then
  blockfile="$(mktemp)"
  printf '%s\n' "$block" > "$blockfile"
  new="$(awk -v s="$start" -v e="$end" -v bf="$blockfile" '$0 == s { while ((getline line < bf) > 0) print line; skip = 1; next } $0 == e { skip = 0; next } !skip { print }' "$doc")"
  rm -f "$blockfile"
else
  new="$(cat "$doc")"$'\n\n## Plumbing test index\n\nOne row per plumbing class of F13 and the test or harness that covers it; generated by `scripts/plumbing-doc.sh`.\n\n'"$block"
fi
if [ "$mode" = "--check" ]; then
  if [ "$new" != "$(cat "$doc")" ]; then echo "PLUMBING DOC STALE"; exit 1; fi
else
  printf '%s\n' "$new" > "$doc"
fi
echo "PLUMBING DOC OK $(printf '%s\n' "$table" | wc -l | tr -d ' ') lines"
