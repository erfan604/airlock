#!/usr/bin/env python3
"""AIR-028: renders contracts/airlock-verdict/harnesses.toml as one table into docs/harnesses.md and between the
harness-table markers of docs/CLAIMS.md, writes the theorem block between the theorem-list markers, and sets the number in
the `KANI OK: <n> harnesses` token of claim row C5 to the harness count.
Usage: python3 scripts/harness-table.py [--check]   (python3 3.11 or later, tomllib, nothing else)
Without --check it writes both files and prints nothing. With --check it regenerates both in memory and prints
`harness table is current` (exit 0) or `STALE: <file>, ...` (exit 1). Exit 2 with a message for a missing or doubled
marker, a missing C5 token or a toml entry missing a field.
Overrides for the tests: HARNESS_TABLE_TOML, HARNESS_TABLE_CLAIMS, HARNESS_TABLE_OUT, HARNESS_TABLE_THEOREMS."""
import os, re, sys, tomllib
from typing import NoReturn

TOML = os.environ.get("HARNESS_TABLE_TOML", "contracts/airlock-verdict/harnesses.toml")
CLAIMS = os.environ.get("HARNESS_TABLE_CLAIMS", "docs/CLAIMS.md")
OUT = os.environ.get("HARNESS_TABLE_OUT", "docs/harnesses.md")
THEOREMS = os.environ.get("HARNESS_TABLE_THEOREMS", "proofs/THEOREMS.txt")

FIELDS = ("name", "property", "statement", "bounds", "exhaustive", "expect", "min_covers", "catches")
HEADER = "| Harness | Property | Statement | Bounds | Exhaustive | Covers | Expectation | Mutants caught |"
SEPARATOR = "| --- | --- | --- | --- | --- | --- | --- | --- |"
PENDING = "Lean theorems: list not generated yet (AIR-030 writes proofs/THEOREMS.txt)."
REPLAY = "Kernel replay and axiom check: scripts/lean-axioms.sh (lake check and lake comparator)."
C5_TOKEN = re.compile(r"KANI OK: \d+ harnesses")


def die(msg) -> NoReturn:
    print(msg)
    sys.exit(2)


def read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return None


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def table_rows(entries):
    rows = [HEADER, SEPARATOR]
    for h in entries:
        missing = [f for f in FIELDS if f not in h]
        if h.get("expect") == "should_panic" and "panic_message" not in h:
            missing.append("panic_message")
        if missing:
            die(f"{TOML}: harness {h.get('name', '(no name)')} lacks {', '.join(missing)}")
        if h["expect"] not in ("success", "should_panic"):
            die(f"{TOML}: harness {h['name']} has expect = {h['expect']!r}, not success or should_panic")
        expectation = "success" if h["expect"] == "success" else f"should_panic: {h['panic_message']}"
        cells = [h["name"], h["property"], h["statement"], h["bounds"], "yes" if h["exhaustive"] is True else "no",
                 h["min_covers"], expectation, ", ".join(h["catches"]) or "-"]
        rows.append("| " + " | ".join(cell(c) for c in cells) + " |")
    return rows


def between(text, name, body):
    start, end = f"<!-- {name}:start -->", f"<!-- {name}:end -->"
    for marker in (start, end):
        n = text.count(marker)
        if n != 1:
            die(f"{CLAIMS}: marker {marker} is {'missing' if n == 0 else 'there ' + str(n) + ' times'}")
    i, j = text.index(start), text.index(end)
    if j < i:
        die(f"{CLAIMS}: {name}:end comes before {name}:start")
    return text[:i + len(start)] + "\n" + body + text[j:]


def render():
    raw = read(TOML)
    if raw is None:
        die(f"{TOML}: not found")
    try:
        entries = tomllib.loads(raw).get("harness", [])
    except tomllib.TOMLDecodeError as e:
        die(f"{TOML}: {e}")
    rows = table_rows(entries)
    out = ("# Kani harnesses\n\nGenerated by scripts/harness-table.py from contracts/airlock-verdict/harnesses.toml; do not edit.\n\n"
           + "\n".join(rows) + "\n")
    claims = read(CLAIMS)
    if claims is None:
        die(f"{CLAIMS}: not found")
    claims = between(claims, "harness-table", "\n".join(rows) + f"\n\nKani harnesses in total: {len(entries)}\n")
    theorems = read(THEOREMS)
    names = [l.strip() for l in (theorems or "").splitlines() if l.strip()]
    block = "\n".join([REPLAY] + [f"- {n}" for n in names]) if theorems is not None else PENDING
    claims = between(claims, "theorem-list", block + "\n")
    lines = claims.split("\n")
    c5 = [i for i, l in enumerate(lines) if l.startswith("| C5 |") and C5_TOKEN.search(l)]
    if not c5:
        die(f"{CLAIMS}: row C5 has no `KANI OK: <n> harnesses` token")
    for i in c5:
        lines[i] = C5_TOKEN.sub(f"KANI OK: {len(entries)} harnesses", lines[i])
    return out, "\n".join(lines)


def main():
    out, claims = render()
    if "--check" in sys.argv[1:]:
        stale = [path for path, text in ((OUT, out), (CLAIMS, claims)) if read(path) != text]
        print(f"STALE: {', '.join(stale)}" if stale else "harness table is current")
        sys.exit(1 if stale else 0)
    for path, text in ((OUT, out), (CLAIMS, claims)):
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


if __name__ == "__main__":
    main()
