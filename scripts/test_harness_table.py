#!/usr/bin/env python3
"""Tests of scripts/harness-table.py (AIR-028). Each test builds a temp directory with a three-entry harnesses.toml, a CLAIMS.md
with both marker pairs and a C5 row, and runs the script through subprocess with the HARNESS_TABLE_* overrides."""
import os, subprocess, sys, tempfile, unittest
from pathlib import Path

SCRIPT = Path(__file__).parent / "harness-table.py"

TOML = '''[[harness]]
name = "p01_untrusted_pc"
property = "P1"
statement = "an untrusted pc never allows"
bounds = "all u16 labels"
exhaustive = true
expect = "success"
min_covers = 2
catches = ["M1", "M4"]

[[harness]]
name = "p07_taint_monotone"
property = "P7"
statement = "taint only grows"
bounds = "unwind 4, three steps"
exhaustive = false
expect = "success"
min_covers = 1
catches = []

[[harness]]
name = "l6a_naive_snapshot"
property = "L6a"
statement = "a naive snapshot exceeds the bound"
bounds = "two requests"
exhaustive = true
expect = "should_panic"
panic_message = "A naive thing exceeds the bound"
min_covers = 1
catches = ["M9"]
'''

CLAIMS = '''# Claims and how to check each one

| # | Claim | Evidence (file:line) | Command | Expected output | Needs | Source ticket |
| --- | --- | --- | --- | --- | --- | --- |
| C5 | the Kani harness table and count | contracts/airlock-verdict/harnesses.toml, docs/harnesses.md | `scripts/kani-check.sh` | `last line: KANI OK: 19 harnesses,` | none | AIR-028 |

## Kani harnesses

<!-- harness-table:start -->
<!-- harness-table:end -->

## Lean theorems

<!-- theorem-list:start -->
<!-- theorem-list:end -->
'''


class HarnessTable(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self.tmp.name)
        self.toml, self.claims = self.dir / "harnesses.toml", self.dir / "CLAIMS.md"
        self.out, self.theorems = self.dir / "harnesses.md", self.dir / "THEOREMS.txt"
        self.toml.write_text(TOML)
        self.claims.write_text(CLAIMS)

    def tearDown(self):
        self.tmp.cleanup()

    def run_script(self, *args):
        env = dict(os.environ, HARNESS_TABLE_TOML=str(self.toml), HARNESS_TABLE_CLAIMS=str(self.claims),
                   HARNESS_TABLE_OUT=str(self.out), HARNESS_TABLE_THEOREMS=str(self.theorems))
        r = subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True, env=env)
        return r.returncode, r.stdout + r.stderr

    def test_fresh_generation_passes_check(self):
        self.assertEqual(self.run_script()[0], 0)
        self.assertEqual(self.run_script("--check"), (0, "harness table is current\n"))

    def test_generated_file_layout(self):
        self.run_script()
        self.assertEqual(self.out.read_text(), (
            "# Kani harnesses\n\n"
            "Generated by scripts/harness-table.py from contracts/airlock-verdict/harnesses.toml; do not edit.\n\n"
            "| Harness | Property | Statement | Bounds | Exhaustive | Covers | Expectation | Mutants caught |\n"
            "| --- | --- | --- | --- | --- | --- | --- | --- |\n"
            "| p01_untrusted_pc | P1 | an untrusted pc never allows | all u16 labels | yes | 2 | success | M1, M4 |\n"
            "| p07_taint_monotone | P7 | taint only grows | unwind 4, three steps | no | 1 | success | - |\n"
            "| l6a_naive_snapshot | L6a | a naive snapshot exceeds the bound | two requests | yes | 1 | "
            "should_panic: A naive thing exceeds the bound | M9 |\n"))

    def test_claims_block_and_total(self):
        self.run_script()
        text = self.claims.read_text()
        start, end = text.index("<!-- harness-table:start -->"), text.index("<!-- harness-table:end -->")
        block = text[start:end]
        self.assertIn("| p07_taint_monotone | P7 |", block)
        self.assertTrue(block.endswith("\n\nKani harnesses in total: 3\n"), block)

    def test_claims_edited_between_markers_is_stale(self):
        self.run_script()
        self.claims.write_text(self.claims.read_text().replace("| P7 |", "| P8 |"))
        code, out = self.run_script("--check")
        self.assertEqual((code, out), (1, f"STALE: {self.claims}\n"))

    def test_generated_file_edited_is_stale(self):
        self.run_script()
        self.out.write_text(self.out.read_text().replace("taint only grows", "taint grows"))
        code, out = self.run_script("--check")
        self.assertEqual((code, out), (1, f"STALE: {self.out}\n"))

    def test_toml_change_makes_both_stale(self):
        self.run_script()
        self.toml.write_text(TOML.replace('statement = "taint', 'statement = "X taint'))
        code, out = self.run_script("--check")
        self.assertEqual((code, out), (1, f"STALE: {self.out}, {self.claims}\n"))

    def test_missing_generated_file_is_stale(self):
        self.run_script()
        self.out.unlink()
        self.assertEqual(self.run_script("--check")[0], 1)

    def test_missing_marker_exits_2(self):
        self.claims.write_text(CLAIMS.replace("<!-- theorem-list:end -->\n", ""))
        code, out = self.run_script()
        self.assertEqual(code, 2)
        self.assertIn("theorem-list:end", out)
        self.assertEqual(self.claims.read_text(), CLAIMS.replace("<!-- theorem-list:end -->\n", ""))

    def test_markers_out_of_order_exit_2(self):
        swapped = CLAIMS.replace("<!-- harness-table:start -->\n<!-- harness-table:end -->",
                                 "<!-- harness-table:end -->\n<!-- harness-table:start -->")
        self.claims.write_text(swapped)
        code, out = self.run_script()
        self.assertEqual(code, 2)
        self.assertIn("harness-table:end comes before harness-table:start", out)

    def test_missing_field_exits_2(self):
        self.toml.write_text(TOML.replace('bounds = "unwind 4, three steps"\n', ""))
        code, out = self.run_script()
        self.assertEqual(code, 2)
        self.assertIn("p07_taint_monotone", out)
        self.assertIn("bounds", out)
        self.assertFalse(self.out.exists())

    def test_should_panic_without_message_exits_2(self):
        self.toml.write_text(TOML.replace('panic_message = "A naive thing exceeds the bound"\n', ""))
        code, out = self.run_script()
        self.assertEqual(code, 2)
        self.assertIn("panic_message", out)

    def test_missing_c5_token_exits_2(self):
        self.claims.write_text(CLAIMS.replace("KANI OK: 19 harnesses,", "KANI OK"))
        code, out = self.run_script()
        self.assertEqual(code, 2)
        self.assertIn("C5", out)

    def test_pipe_and_newline_escaped(self):
        self.toml.write_text(TOML.replace('statement = "taint only grows"', 'statement = "taint a | b\\nonly grows"'))
        self.run_script()
        self.assertIn("| taint a \\| b only grows |", self.out.read_text())

    def test_c5_number_mismatch_fails_and_is_repaired(self):
        self.run_script()
        self.claims.write_text(self.claims.read_text().replace("KANI OK: 3 harnesses", "KANI OK: 19 harnesses"))
        self.assertEqual(self.run_script("--check")[0], 1)
        self.assertEqual(self.run_script()[0], 0)
        row = [l for l in self.claims.read_text().splitlines() if l.startswith("| C5 |")][0]
        self.assertIn("`last line: KANI OK: 3 harnesses,`", row)
        self.assertEqual(self.run_script("--check")[0], 0)

    def test_c5_number_only_in_c5_row(self):
        self.claims.write_text(CLAIMS.replace("## Kani harnesses", "Note: KANI OK: 7 harnesses was the spike.\n\n## Kani harnesses"))
        self.assertEqual(self.run_script()[0], 0)
        self.assertIn("KANI OK: 7 harnesses was the spike", self.claims.read_text())
        self.assertIn("KANI OK: 3 harnesses,", self.claims.read_text())

    def test_theorem_block_pending_then_names(self):
        self.run_script()
        pending = "Lean theorems: list not generated yet (AIR-030 writes proofs/THEOREMS.txt)."
        self.assertIn(f"<!-- theorem-list:start -->\n{pending}\n<!-- theorem-list:end -->", self.claims.read_text())
        self.theorems.write_text("allow_iff\np7_taint_monotone\n")
        self.assertEqual(self.run_script("--check")[0], 1)
        self.run_script()
        self.assertIn("<!-- theorem-list:start -->\n"
                      "Kernel replay and axiom check: scripts/lean-axioms.sh (lake check and lake comparator).\n"
                      "- allow_iff\n- p7_taint_monotone\n<!-- theorem-list:end -->", self.claims.read_text())
        self.assertNotIn(pending, self.claims.read_text())

    def test_empty_theorems_file_is_not_the_pending_form(self):
        self.theorems.write_text("")
        self.run_script()
        self.assertIn("<!-- theorem-list:start -->\n"
                      "Kernel replay and axiom check: scripts/lean-axioms.sh (lake check and lake comparator).\n"
                      "<!-- theorem-list:end -->", self.claims.read_text())

    def test_unknown_expect_exits_2(self):
        self.toml.write_text(TOML.replace('expect = "success"\nmin_covers = 2', 'expect = "maybe"\nmin_covers = 2'))
        code, out = self.run_script()
        self.assertEqual(code, 2)
        self.assertIn("maybe", out)

    def test_regeneration_is_idempotent(self):
        self.run_script()
        first = self.claims.read_text()
        self.run_script()
        self.assertEqual(self.claims.read_text(), first)
        self.assertEqual(first.count("<!-- harness-table:start -->"), 1)
        self.assertEqual(first.count("| Harness | Property |"), 1)


if __name__ == "__main__":
    unittest.main()
